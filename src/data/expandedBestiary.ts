// Build EXPANDED_MONSTERS and EXPANDED_ITEMS deterministically from seeds
export const EXPANDED_MONSTERS: Monster[] = [];
export const EXPANDED_ITEMS: Record<string, GameItem> = {};

EXPANDED_MONSTER_SEEDS.forEach((seed) => {
  const minLevel =
    seed.cr <= 3
      ? 1
      : seed.cr <= 6
      ? 2
      : seed.cr <= 10
      ? 3
      : seed.cr <= 14
      ? 4
      : seed.cr <= 17
      ? 5
      : 6;

  const staminaCost = seed.cr <= 4 ? 1 : seed.cr <= 11 ? 2 : 3;

  // Realistic D&D 5e Hunt DCs scaled by CR!
  const commonDc = Math.min(18, Math.max(11, Math.round(10 + seed.cr * 0.45)));
  const rareDc = Math.min(22, commonDc + 4);
  const legendaryDc = Math.min(26, commonDc + 8);

  const drop0Id = `${seed.id}_${seed.drops[0].suffixId}`;
  const drop1Id = `${seed.id}_${seed.drops[1].suffixId}`;
  const drop2Id = `${seed.id}_${seed.drops[2].suffixId}`;

  EXPANDED_MONSTERS.push({
    id: seed.id,
    name: seed.name,
    nameEn: seed.nameEn,
    cr: seed.cr,
    crDisplay: `CR ${seed.cr}`,
    creatureType: seed.creatureType,
    biome: seed.biome,
    staminaCost,
    minAlchemistLevel: minLevel,
    icon: seed.icon,
    accentColor: seed.accentColor,
    lore: seed.lore,
    drops: [
      { tier: 'common', dc: commonDc, itemId: drop0Id },
      { tier: 'rare', dc: rareDc, itemId: drop1Id },
      { tier: 'legendary', dc: legendaryDc, itemId: drop2Id },
    ],
  });

  // 1. Common reagent
  EXPANDED_ITEMS[drop0Id] = {
    id: drop0Id,
    name: seed.drops[0].name,
    nameEn: seed.drops[0].nameEn,
    kind: 'reagent',
    rarity: seed.cr >= 12 ? 'uncommon' : 'common',
    icon: seed.drops[0].icon,
    material: seed.drops[0].material,
    elements: [seed.elements[0]],
    powerLevel: Math.min(20, Math.max(1, seed.cr)),
    goldValue: Math.round(15 + seed.cr * 5),
    monsterId: seed.id,
    monsterName: seed.name,
    harvestDc: commonDc,
    description: seed.drops[0].desc,
  };

  // 2. Rare reagent
  EXPANDED_ITEMS[drop1Id] = {
    id: drop1Id,
    name: seed.drops[1].name,
    nameEn: seed.drops[1].nameEn,
    kind: 'reagent',
    rarity: seed.cr >= 14 ? 'very_rare' : 'rare',
    icon: seed.drops[1].icon,
    material: seed.drops[1].material,
    elements: [seed.elements[0], seed.elements[1]],
    powerLevel: Math.min(20, Math.max(3, seed.cr + 2)),
    goldValue: Math.round(40 + seed.cr * 12),
    monsterId: seed.id,
    monsterName: seed.name,
    harvestDc: rareDc,
    description: seed.drops[1].desc,
  };

  // 3. Legendary reagent
  EXPANDED_ITEMS[drop2Id] = {
    id: drop2Id,
    name: seed.drops[2].name,
    nameEn: seed.drops[2].nameEn,
    kind: 'reagent',
    rarity: seed.cr >= 17 ? 'artifact' : 'legendary',
    icon: seed.drops[2].icon,
    material: seed.drops[2].material,
    elements: [seed.elements[1], seed.elements[0]],
    powerLevel: Math.min(20, Math.max(6, seed.cr + 4)),
    goldValue: Math.round(110 + seed.cr * 25),
    monsterId: seed.id,
    monsterName: seed.name,
    harvestDc: legendaryDc,
    description: seed.drops[2].desc,
  };
});

